"""Professional detailed PDF report (management + environmental reporting).

Kept separate from services/reports.py so the original, tested CSV/PDF module stays untouched.
Uses the SAME summarize() path as the dashboard (only calculated rows count) and draws charts
inside the PDF itself (reportlab vector graphics - no browser needed).
"""
from __future__ import annotations

import io
from datetime import date

import pandas as pd

from services import ledger as L
from services.reports import PdfUnavailable, _find_font, arabic_pdf_supported


def _fmt_num(v, digits: int = 2) -> str:
    try:
        return f"{float(v):,.{digits}f}"
    except (TypeError, ValueError):
        return "—"


def _drawing_bar(title: str, labels: list, values: list, font: str, color="#047857"):
    from reportlab.graphics.charts.barcharts import VerticalBarChart
    from reportlab.graphics.shapes import Drawing, String
    from reportlab.lib import colors as _colors
    d = Drawing(470, 150)
    d.add(String(0, 138, title, fontName=font, fontSize=10))
    if not values:
        d.add(String(0, 100, "no data", fontName=font, fontSize=8, fillColor=_colors.grey))
        return d
    ch = VerticalBarChart()
    ch.x, ch.y, ch.width, ch.height = 10, 18, 450, 105
    ch.data = [values]
    ch.categoryAxis.categoryNames = [str(x)[:16] for x in labels]
    ch.categoryAxis.labels.fontName = font
    ch.categoryAxis.labels.fontSize = 7
    ch.valueAxis.labels.fontName = font
    ch.valueAxis.labels.fontSize = 7
    ch.bars[0].fillColor = _colors.HexColor(color)
    ch.barSpacing = 2
    d.add(ch)
    return d


def _drawing_line(title: str, labels: list, values: list, font: str):
    from reportlab.graphics.charts.linecharts import HorizontalLineChart
    from reportlab.graphics.shapes import Drawing, String
    from reportlab.lib import colors as _colors
    d = Drawing(470, 150)
    d.add(String(0, 138, title, fontName=font, fontSize=10))
    if len(values) < 2:
        d.add(String(0, 100, "not enough data for a trend", fontName=font, fontSize=8,
                     fillColor=_colors.grey))
        return d
    ch = HorizontalLineChart()
    ch.x, ch.y, ch.width, ch.height = 10, 18, 450, 105
    ch.data = [values]
    ch.categoryAxis.categoryNames = [str(x)[:10] for x in labels]
    ch.categoryAxis.labels.fontName = font
    ch.categoryAxis.labels.fontSize = 7
    ch.valueAxis.labels.fontName = font
    ch.valueAxis.labels.fontSize = 7
    ch.lines[0].strokeColor = _colors.HexColor("#6d28d9")
    ch.lines[0].strokeWidth = 2
    d.add(ch)
    return d


def pdf_detailed(df: pd.DataFrame, *, title_company: str = "", title_facility: str = "",
                 period: str = "", country: str = "", lang: str = "en", plans=(),
                 targets=(), facility_totals=None, generated_by: str = "",
                 yearly=None) -> bytes:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4, landscape
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

    ar = lang == "ar"
    font = "Helvetica"
    if ar:
        ok, why = arabic_pdf_supported()
        if not ok:
            raise PdfUnavailable(why)
        import arabic_reshaper
        from bidi.algorithm import get_display
        pdfmetrics.registerFont(TTFont("CarbonFont", _find_font()))
        font = "CarbonFont"
        shape = lambda t: get_display(arabic_reshaper.reshape(str(t)))
    else:
        shape = lambda t: str(t)

    T = {
        "title": ("CarbonAI Carbon Emissions Management Report", "تقرير إدارة الانبعاثات الكربونية - CarbonAI"),
        "subtitle": ("Detailed report", "تقرير تفصيلي"),
        "company": ("Organisation", "المنشأة"), "facility": ("Facility", "الفرع"),
        "period": ("Reporting period", "فترة التقرير"), "generated": ("Generated on", "تاريخ الإنشاء"),
        "by": ("Generated by", "أُنشئ بواسطة"),
        "summary": ("Executive summary", "الملخص التنفيذي"),
        "total": ("Total emissions", "إجمالي الانبعاثات"),
        "scopes": ("Emissions by scope", "الانبعاثات حسب النطاق"),
        "scope": ("Scope", "النطاق"), "kg": ("kg CO2e", "كجم CO2e"),
        "t": ("tonne CO2e", "طن CO2e"), "share": ("Share", "النسبة"),
        "facilities": ("Emissions by facility", "الانبعاثات حسب المصنع"),
        "categories": ("Emissions by activity category", "الانبعاثات حسب فئة النشاط"),
        "top": ("Main emission sources", "أهم مصادر الانبعاثات"),
        "trend": ("Monthly emissions trend", "اتجاه الانبعاثات الشهري"),
        "dist": ("Scope distribution", "توزيع النطاقات"),
        "yearly": ("Annual comparison", "المقارنة السنوية"),
        "year": ("Year", "السنة"),
        "plans": ("Emission reduction plans", "خطط خفض الانبعاثات"),
        "targets": ("Reduction targets", "أهداف الخفض"),
        "method": ("Methodology and data quality", "المنهجية وجودة البيانات"),
        "limits": ("Assumptions and limitations", "الافتراضات والقيود"),
        "records": ("Records reviewed", "السجلات"), "calculated": ("Calculated records", "السجلات المحسوبة"),
        "review": ("Needs review", "تحتاج مراجعة"),
        "verified": ("Records with verified factor", "سجلات بمعامل موثق"),
        "no_plans": ("No reduction plans recorded.", "لا توجد خطط خفض مسجلة."),
        "no_targets": ("No reduction targets recorded.", "لا توجد أهداف خفض مسجلة."),
        "activity": ("Activity", "النشاط"), "priority": ("Priority", "الأولوية"),
        "status": ("Status", "الحالة"), "owner": ("Owner", "المسؤول"),
        "target_year": ("Target year", "سنة الهدف"), "baseline": ("Baseline", "الأساس"),
        "target": ("Target", "الهدف"), "reduction": ("Reduction", "الخفض"),
        "unscoped": ("Unscoped", "غير مصنف"),
    }
    txt = lambda k: shape(T[k][1] if ar else T[k][0])
    align = 2 if ar else 0
    body = ParagraphStyle("body", fontName=font, fontSize=8.5, leading=11.5, alignment=align)
    h1 = ParagraphStyle("h1", fontName=font, fontSize=15, leading=19, alignment=align)
    h2 = ParagraphStyle("h2", fontName=font, fontSize=11, leading=14, alignment=align,
                        spaceBefore=8, spaceAfter=2)
    small = ParagraphStyle("small", fontName=font, fontSize=7.5, leading=10, alignment=align)

    s = L.summarize(df)
    total = float(s["total_kg"]) or 0.0
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=landscape(A4), leftMargin=24, rightMargin=24,
                            topMargin=22, bottomMargin=22, title="CarbonAI detailed report")
    el = [Paragraph(txt("title"), h1), Paragraph(txt("subtitle"), body), Spacer(1, 4)]
    meta = [(txt("company"), title_company or "-"), (txt("facility"), title_facility or "-"),
            (txt("period"), period or "-"), (txt("generated"), date.today().isoformat())]
    if generated_by:
        meta.append((txt("by"), generated_by))
    el.append(Table([[Paragraph(shape(v), body), Paragraph(k, body)] if ar else
                     [Paragraph(k, body), Paragraph(shape(v), body)] for k, v in meta],
                    colWidths=[130, 300]))
    el += [Spacer(1, 4), Paragraph(txt("summary"), h2)]
    el.append(Paragraph(
        f"{txt('total')}: {_fmt_num(total)} kg CO2e / {_fmt_num(total / 1000, 3)} t CO2e  |  "
        f"{txt('records')}: {s['records']}  |  {txt('calculated')}: {s['calculated']}  |  "
        f"{txt('review')}: {s['needs_review']}  |  {txt('verified')}: {s['verified_factor_records']}",
        body))

    el.append(Paragraph(txt("scopes"), h2))
    rows = [[txt("scope"), txt("kg"), txt("t"), txt("share")]]
    for sc in ("Scope 1", "Scope 2", "Scope 3"):
        kg = float(s["by_scope_kg"][sc])
        rows.append([sc, _fmt_num(kg), _fmt_num(kg / 1000, 3),
                     f"{100 * kg / total:.1f}%" if total else "—"])
    if s["unscoped_kg"]:
        kg = float(s["unscoped_kg"])
        rows.append([txt("unscoped"), _fmt_num(kg), _fmt_num(kg / 1000, 3),
                     f"{100 * kg / total:.1f}%" if total else "—"])
    tb = Table(rows, repeatRows=1, colWidths=[170, 110, 110, 80])
    tb.setStyle(TableStyle([("FONTNAME", (0, 0), (-1, -1), font), ("FONTSIZE", (0, 0), (-1, -1), 8),
                            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#064e3b")),
                            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                            ("GRID", (0, 0), (-1, -1), 0.25, colors.grey),
                            ("ALIGN", (1, 1), (-1, -1), "RIGHT")]))
    el.append(tb)

    scope_labels = ["Scope 1", "Scope 2", "Scope 3"]
    scope_vals = [float(s["by_scope_kg"][k]) for k in scope_labels]
    el.append(Spacer(1, 6))
    el.append(_drawing_bar(txt("dist"), scope_labels, scope_vals, font))
    monthly = list(s["monthly_kg"].items())
    if monthly:
        el.append(_drawing_line(txt("trend"),
                                [f"{y}-{m:02d}" for (y, m), _ in monthly][-18:],
                                [float(v) for _, v in monthly][-18:], font))

    if facility_totals:
        el.append(Paragraph(txt("facilities"), h2))
        frows = [[txt("facility"), txt("kg"), txt("t")]]
        for name, kg in facility_totals[:15]:
            frows.append([shape(name), _fmt_num(kg), _fmt_num(kg / 1000, 3)])
        ft = Table(frows, repeatRows=1, colWidths=[260, 120, 120])
        ft.setStyle(TableStyle([("FONTNAME", (0, 0), (-1, -1), font), ("FONTSIZE", (0, 0), (-1, -1), 8),
                                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#064e3b")),
                                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                                ("GRID", (0, 0), (-1, -1), 0.25, colors.grey)]))
        el.append(ft)
        el.append(_drawing_bar(txt("facilities"), [shape(n)[:14] for n, _ in facility_totals[:10]],
                               [float(kg) for _, kg in facility_totals[:10]], font))

    if yearly:
        el.append(Paragraph(txt("yearly"), h2))
        yrows = [[txt("year"), txt("kg"), txt("t")]]
        for y, kg in yearly:
            yrows.append([str(y), _fmt_num(kg), _fmt_num(kg / 1000, 3)])
        yt = Table(yrows, repeatRows=1, colWidths=[90, 140, 140])
        yt.setStyle(TableStyle([("FONTNAME", (0, 0), (-1, -1), font), ("FONTSIZE", (0, 0), (-1, -1), 8),
                                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#064e3b")),
                                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                                ("GRID", (0, 0), (-1, -1), 0.25, colors.grey)]))
        el.append(yt)
        el.append(_drawing_bar(txt("yearly"), [str(y) for y, _ in yearly],
                               [float(kg) for _, kg in yearly], font))

    if not df.empty and "category_key" in df.columns:
        calc = df[df["calc_status"] == "calculated"]
        cats = {}
        for key, g in calc.groupby("category_key", dropna=False):
            cats[key or "other"] = float(L._sum(g["kg"]))
        if cats:
            el.append(Paragraph(txt("categories"), h2))
            crows = [[txt("activity"), txt("kg")]]
            for k, v in sorted(cats.items(), key=lambda x: -x[1])[:12]:
                crows.append([k, _fmt_num(v)])
            ct = Table(crows, repeatRows=1, colWidths=[240, 130])
            ct.setStyle(TableStyle([("FONTNAME", (0, 0), (-1, -1), font), ("FONTSIZE", (0, 0), (-1, -1), 8),
                                    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#064e3b")),
                                    ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                                    ("GRID", (0, 0), (-1, -1), 0.25, colors.grey)]))
            el.append(ct)

    top = L.top_sources(df, n=10)
    if top:
        el.append(Paragraph(txt("top"), h2))
        trows = [[txt("activity"), txt("kg"), txt("share")]]
        for name, kg in top:
            v = float(kg)
            trows.append([shape(name)[:60], _fmt_num(v), f"{100 * v / total:.1f}%" if total else "—"])
        tt = Table(trows, repeatRows=1, colWidths=[300, 110, 80])
        tt.setStyle(TableStyle([("FONTNAME", (0, 0), (-1, -1), font), ("FONTSIZE", (0, 0), (-1, -1), 8),
                                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#064e3b")),
                                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                                ("GRID", (0, 0), (-1, -1), 0.25, colors.grey)]))
        el.append(tt)

    el.append(Paragraph(txt("plans"), h2))
    if plans:
        prows = [[txt("activity"), txt("priority"), txt("status"), txt("owner")]]
        for p in plans[:12]:
            prows.append([shape((p.get("description") or p.get("area") or "")[:70]),
                          p.get("priority") or "—", p.get("status") or "—",
                          shape(p.get("owner") or "—")])
        pt = Table(prows, repeatRows=1, colWidths=[330, 70, 70, 120])
        pt.setStyle(TableStyle([("FONTNAME", (0, 0), (-1, -1), font), ("FONTSIZE", (0, 0), (-1, -1), 8),
                                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#064e3b")),
                                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                                ("GRID", (0, 0), (-1, -1), 0.25, colors.grey)]))
        el.append(pt)
    else:
        el.append(Paragraph(txt("no_plans"), body))

    el.append(Paragraph(txt("targets"), h2))
    if targets:
        trows = [[txt("target_year"), txt("baseline"), txt("target"), txt("reduction")]]
        for t in targets[:8]:
            trows.append([str(t["target_year"]), f"{_fmt_num(t['baseline_kg_co2e'])} kg",
                          f"{_fmt_num(t['target_kg_co2e'])} kg",
                          f"{t['target_reduction_pct']:.1f}%" if t.get("target_reduction_pct") is not None else "—"])
        tg = Table(trows, repeatRows=1, colWidths=[90, 140, 140, 110])
        tg.setStyle(TableStyle([("FONTNAME", (0, 0), (-1, -1), font), ("FONTSIZE", (0, 0), (-1, -1), 8),
                                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#064e3b")),
                                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                                ("GRID", (0, 0), (-1, -1), 0.25, colors.grey)]))
        el.append(tg)
    else:
        el.append(Paragraph(txt("no_targets"), body))

    el.append(Paragraph(txt("method"), h2))
    el.append(Paragraph(
        "Emissions are computed by the deterministic engine as activity quantity x factor, with "
        "dimension-checked unit conversion. Only rows whose calc_status is 'calculated' are summed; "
        "rows needing a factor/date/review are listed separately and never counted as zero. Factor "
        "values and sources are snapshotted per record, so later library updates never alter history.",
        small))
    el.append(Paragraph(txt("limits"), h2))
    el.append(Paragraph(
        "Unverified, user-supplied or proxy factors produce estimates (flagged per record). Scope "
        "assignments marked 'suggested' follow GHG Protocol rules and should be reviewed. Totals "
        "exclude records that could not be calculated. Data coverage for Egypt is tracked in the "
        "coverage matrix; international defaults are labelled as such and never presented as "
        "Egyptian official factors.", small))
    doc.build(el)
    return buf.getvalue()
